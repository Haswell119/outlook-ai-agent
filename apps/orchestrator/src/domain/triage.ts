/**
 * Greeting and sign-off lines, stripped before measuring "how short is this
 * really". Both require a *short* remainder and no question mark, so
 * "Thanks — can you confirm the deadline?" stays: it is a real question that
 * happens to open with a courtesy word.
 */
const GREETING_LINE = /^(bonjour|bonsoir|salut|hello|hi|hey|dear|cher|chère|chers|coucou|good (morning|afternoon|evening))\b[^?]{0,40}$/i;
/**
 * A sign-off line: a closing word followed by punctuation or at most a dozen
 * characters. The tight remainder is what separates "Merci." (a sign-off) from
 * "Thanks, here is the document you asked for." (content that opens politely).
 * Everything after a sign-off is a signature block, so scanning stops there.
 */
const SIGNOFF_LINE =
  /^(merci|thanks|thx|thank you|regards|best regards|kind regards|warm regards|cordialement|bien cordialement|sincèrement|sincerely|meilleures salutations|salutations|cheers|bien à vous|bien a vous)\b[^?!]{0,12}$|^(envoyé de mon|envoye de mon|sent from my|get outlook for|obtenez outlook pour)\b.{0,40}$|^(--+|__+)$/i;

export interface TriageOptions {
  /** Domains considered internal; internal senders are never triaged as newsletters. */
  internalDomains?: string[];
}

const localPart = (address: string | undefined): string => (address ?? "").toLowerCase().split("@")[0] ?? "";
const hasAny = (haystack: string, needles: string[]): string | undefined => needles.find((n) => haystack.includes(n));

/** Body with greetings, sign-offs, signature names and empty lines removed — what is actually said. */
export function coreBodyText(body: string): string {
  const lines = normalizeWhitespace(body)
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0);
  const kept: string[] = [];
  for (const line of lines) {
    if (GREETING_LINE.test(line)) continue;
    // A sign-off ends the message: what follows is a signature, not content.
    if (SIGNOFF_LINE.test(line)) break;
    kept.push(line);
  }
  return kept.join(" ").trim();
}

/** Classify an email with pure heuristics. Never throws, never does I/O. */
export function triageEmail(email: EmailContext, opts: TriageOptions = {}): TriageResult {
  const subject = (email.subject ?? "").trim();
  const subjectLower = subject.toLowerCase();
  const body = email.body ?? "";
  const bodyLower = body.toLowerCase();
  const all = `${subjectLower}\n${bodyLower}`;
  const sender = (email.from?.address ?? "").toLowerCase();
  const local = localPart(sender);
  const attachmentNames = email.attachments.map((a) => (a.name ?? "").toLowerCase());
  const attachmentTypes = email.attachments.map((a) => (a.contentType ?? "").toLowerCase());
  const categories = email.categories.map((c) => c.toLowerCase());

  const conv = (reason: string, confidence = 0.6): TriageResult => ({ kind: "conversation", reason, confidence, skipModel: false });
  const skip = (kind: TriageKind, reason: string, confidence: number): TriageResult => ({ kind, reason, confidence, skipModel: true });

  /* 1. Out of office / auto-reply — the sender is a human but nothing is asked. */
  const oooSubject = hasAny(subjectLower, OOO_MARKERS);
  if (oooSubject) return skip("out_of_office", `subject:${oooSubject}`, 0.85);
  const oooBody = hasAny(bodyLower.slice(0, 600), OOO_MARKERS);
  if (oooBody && body.length < 1500) return skip("out_of_office", `body:${oooBody}`, 0.7);

  /* 2. Calendar invites / responses. */
  if (attachmentTypes.some((t) => t.includes("text/calendar")) || attachmentNames.some((n) => n.endsWith(".ics"))) return skip("calendar", "attachment:ics", 0.9);
  const calPrefix = CALENDAR_SUBJECT_PREFIXES.find((p) => subjectLower.startsWith(p));
  if (calPrefix) return skip("calendar", `subject:${calPrefix}`, 0.8);
  if (bodyLower.includes("begin:vcalendar")) return skip("calendar", "body:vcalendar", 0.9);
  const calMarkers = CALENDAR_BODY_MARKERS.filter((m) => bodyLower.includes(m));
  if (calMarkers.length >= 2 && /\b(meeting|réunion|reunion|invitation|appointment|rendez-vous)\b/i.test(all)) return skip("calendar", `body:${calMarkers.slice(0, 2).join("+")}`, 0.65);

  /* 3. Newsletters / marketing (List-Unsubscribe equivalents). */
  const unsub = hasAny(bodyLower, UNSUBSCRIBE_MARKERS);
  const internal = isInternal(sender, opts.internalDomains ?? []);
  if (unsub && !internal) return skip("newsletter", `body:${unsub}`, 0.85);
  if (unsub && internal && NEWSLETTER_LOCALPARTS.includes(local)) return skip("newsletter", `internal-sender:${local}`, 0.7);
  if (!internal && NEWSLETTER_LOCALPARTS.includes(local) && /\b(newsletter|weekly|monthly|digest|bulletin|webinar|webinaire|invitation to|promotion|offre|discover|découvrez)\b/i.test(all)) {
    return skip("newsletter", `sender:${local}`, 0.65);
  }
  if (categories.some((c) => c.includes("newsletter"))) return skip("newsletter", "category:newsletter", 0.6);

  /* 4. Machine-generated messages (delivery reports, "do not reply"). */
  const autoMarker = hasAny(all, AUTOMATIC_MARKERS);
  if (autoMarker) return skip("automatic", `body:${autoMarker}`, 0.75);

  /* 5. System notifications from a robot sender. */
  const robot = ROBOT_LOCALPARTS.find((r) => local === r || local.startsWith(`${r}.`) || local.startsWith(`${r}-`) || local.startsWith(`${r}_`) || local.includes(r));
  if (robot) return skip("notification", `sender:${robot}`, 0.8);
  if (/^\s*\[(?:[\w .-]{2,24})\]/.test(subject) && !internal && /\b(ticket|issue|alert|alerte|build|deploy|incident|case|request #|jira|servicenow)\b/i.test(all)) {
    return skip("notification", "subject:tagged-system", 0.6);
  }

  /* 6. Trivial acknowledgements — nothing to summarise. */
  const core = coreBodyText(body);
  const hasAttachment = email.attachments.some((a) => !a.isInline);
  if (!hasAttachment && !core.includes("?")) {
    if (core.length === 0 && subject.length > 0) return skip("trivial", "body:empty", 0.6);
    if (core.length <= 160 && TRIVIAL_PATTERNS.some((re) => re.test(core.replace(/\s+/g, " ").trim()))) return skip("trivial", "body:acknowledgement", 0.75);
    if (core.length <= 25) return skip("trivial", "body:too-short", 0.55);
  }

  return conv("default", 0.6);
}

function isInternal(address: string, internalDomains: string[]): boolean {
  const at = address.lastIndexOf("@");
  if (at < 0) return false;
  const domain = address.slice(at + 1);
  return internalDomains.some((d) => {
    const dd = d.toLowerCase();
    return domain === dd || domain.endsWith(`.${dd}`);
  });
}

