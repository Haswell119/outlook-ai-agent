/**
 * Triage — the first and cheapest line of AI-load minimisation.
 *
 * Every inbound email is classified here, with **pure heuristics only**, before
 * any model call. Only `conversation` emails are worth a model call; for every
 * other kind the orchestrator answers from `triageAnalysis()` below
 * (`source: "heuristic"`), which costs zero GPU time.
 *
 * Inputs are the fields the add-in / Graph always give us: sender, subject,
 * body text, attachment metadata and Outlook categories. `EmailContext` carries
 * no raw MIME headers, so header-level signals (`List-Unsubscribe`,
 * `Auto-Submitted`, `X-Auto-Response-Suppress`, `Content-Type: text/calendar`)
 * are recognised through their body/sender/attachment equivalents — Outlook and
 * Graph surface them as visible footers, sender conventions and `.ics` parts.
 *
 * Ordering matters: the more specific a kind, the earlier it is tested.
 * An out-of-office reply from `noreply@` is an out-of-office, not a notification.
 */

export type TriageKind = NonNullable<EmailAnalysis["triage"]>["kind"];

export interface TriageResult {
  kind: TriageKind;
  /** Short machine-readable reason, e.g. `sender:noreply` or `body:unsubscribe`. */
  reason: string;
  /** Honest confidence of the *classification* (not of the summary). */
  confidence: number;
  /** True when no model call is needed. */
  skipModel: boolean;
}

